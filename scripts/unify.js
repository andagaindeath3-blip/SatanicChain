#!/usr/bin/env node
const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..');
const cfg = JSON.parse(fs.readFileSync(path.join(ROOT, 'config/chain.json'), 'utf8'));
const satanicRpc = process.env.RPC_SATANIC || cfg.rpc.http;
const chains = [{
  key: 'satanic', name: cfg.name + ' L1', chainId: cfg.chainId,
  rpc: satanicRpc, explorer: cfg.explorer, currency: cfg.symbol,
}];
const NAMES = {
  ethereum: 'Ethereum', bsc: 'BNB Smart Chain', base: 'Base',
  arbitrum: 'Arbitrum One', optimism: 'OP Mainnet', polygon: 'Polygon',
  avalanche: 'Avalanche C-Chain', sepolia: 'Ethereum Sepolia',
};
for (const [key, c] of Object.entries(cfg.publicRpcs)) {
  chains.push({
    key, name: NAMES[key] || key,
    chainId: c.id,
    rpc: process.env['RPC_' + key.toUpperCase()] || c.rpc,
    explorer: c.explorer, currency: c.currency, testnet: !!c.testnet,
  });
}
const netLines = chains.map((c) => {
  const rpcExpr = c.key === 'satanic' ? 'SATANIC_RPC' : JSON.stringify(c.rpc);
  return '  { key: ' + JSON.stringify(c.key) + ', name: ' + JSON.stringify(c.name) +
    ', chainId: ' + c.chainId + ', rpc: ' + rpcExpr +
    ', explorer: ' + JSON.stringify(c.explorer) +
    ', currency: ' + JSON.stringify(c.currency) +
    (c.testnet ? ', testnet: true' : '') + ' }';
});
fs.writeFileSync(path.join(ROOT, 'scripts/networks.js'),
  '// AUTO-GENERATED by npm run unify\nconst { SATANIC_RPC } = require(\'./rpc\');\nmodule.exports = [\n' +
  netLines.join(',\n') + '\n];\n');
const adminNet = chains.map((c) => ({
  key: c.key, name: c.name, chainId: c.chainId, rpc: c.rpc,
  explorer: c.explorer, currency: c.currency, testnet: c.testnet || false,
}));
fs.writeFileSync(path.join(ROOT, 'admin/networks.js'),
  '// AUTO-GENERATED by npm run unify\nwindow.NETWORKS = ' + JSON.stringify(adminNet, null, 2) + ';\n');
const dappChains = chains.map((c) => ({
  id: c.chainId, name: c.name.replace(' L1', ''), rpc: c.rpc,
  explorer: c.explorer, currency: c.currency,
}));
fs.writeFileSync(path.join(ROOT, 'dapp/config.js'),
  '// AUTO-GENERATED by npm run unify\nwindow.DAPP_CONFIG = ' + JSON.stringify({
    projectId: '', defaultChainId: cfg.chainId, appName: cfg.name,
    appUrl: 'https://satanicchain.app', logo: 'logo.gif',
    rateSatanToSusd: cfg.rateSatanToSusd, deployments: {},
    chains: dappChains,
    bridge: { minAmount: '1', relayerNote: 'release after relayer confirmation' },
  }, null, 2).replace('"https://satanicchain.app"',
    "typeof location !== 'undefined' ? location.origin : 'https://satanicchain.app'") + ';\n');
fs.writeFileSync(path.join(ROOT, 'dapp/chain.json'), JSON.stringify({
  chainId: cfg.chainId, chainIdHex: cfg.chainIdHex, chainName: cfg.name,
  nativeCurrency: { name: cfg.symbol, symbol: cfg.symbol, decimals: cfg.decimals },
  rpcUrls: [cfg.rpc.http, cfg.rpc.avalanche],
  blockExplorerUrls: [cfg.explorer],
}, null, 2) + '\n');
fs.writeFileSync(path.join(ROOT, 'chain.config.json'), JSON.stringify({
  name: cfg.name, symbol: cfg.symbol, chainId: cfg.chainId, decimals: cfg.decimals,
  blockTime: cfg.blockTime, gasLimit: cfg.gasLimit,
  modes: { geth: { rpc: cfg.rpc.http, ws: cfg.rpc.ws }, avalanche: { rpc: cfg.rpc.avalanche } },
  explorer: cfg.explorer, rateSatanToSusd: cfg.rateSatanToSusd, prefund: cfg.prefund,
}, null, 2) + '\n');
fs.writeFileSync(path.join(ROOT, 'scripts/rpc.js'),
`const CHAIN = {
  name: ${JSON.stringify(cfg.name)}, chainId: ${cfg.chainId}, chainIdHex: ${JSON.stringify(cfg.chainIdHex)},
  symbol: ${JSON.stringify(cfg.symbol)}, decimals: ${cfg.decimals},
  explorer: process.env.EXPLORER_SATANIC || ${JSON.stringify(cfg.explorer)},
};
const SATANIC_RPC = process.env.RPC_SATANIC || process.env.RPC_URL || ${JSON.stringify(cfg.rpc.http)};
const SATANIC_WS = process.env.WS_SATANIC || ${JSON.stringify(cfg.rpc.ws)};
const PUBLIC = {
  ethereum: process.env.RPC_ETHEREUM || ${JSON.stringify(cfg.publicRpcs.ethereum.rpc)},
  bsc: process.env.RPC_BSC || ${JSON.stringify(cfg.publicRpcs.bsc.rpc)},
  polygon: process.env.RPC_POLYGON || ${JSON.stringify(cfg.publicRpcs.polygon.rpc)},
  arbitrum: process.env.RPC_ARBITRUM || ${JSON.stringify(cfg.publicRpcs.arbitrum.rpc)},
  optimism: process.env.RPC_OPTIMISM || ${JSON.stringify(cfg.publicRpcs.optimism.rpc)},
  base: process.env.RPC_BASE || ${JSON.stringify(cfg.publicRpcs.base.rpc)},
  avalanche: process.env.RPC_AVALANCHE || ${JSON.stringify(cfg.publicRpcs.avalanche.rpc)},
  sepolia: process.env.RPC_SEPOLIA || ${JSON.stringify(cfg.publicRpcs.sepolia.rpc)},
};
function satanicWalletAdd(rpcUrl) {
  return {
    chainId: CHAIN.chainIdHex, chainName: CHAIN.name,
    nativeCurrency: { name: 'SATAN', symbol: 'SATAN', decimals: 18 },
    rpcUrls: [rpcUrl || SATANIC_RPC],
    blockExplorerUrls: CHAIN.explorer ? [CHAIN.explorer] : [],
  };
}
module.exports = { CHAIN, SATANIC_RPC, SATANIC_WS, PUBLIC, satanicWalletAdd };
`);
console.log('Unified OK — L1', satanicRpc, 'chainId', cfg.chainId);
